/**
 * Bundles the browser half into `dist/client/client.js`, wrapped in the loader
 * envelope the DSH web app expects:
 *
 *   window.__ModuleLoader__.load({ id, factory: (require) => module.exports })
 *
 * `react` and `react/jsx-runtime` stay external: the host's module table
 * provides them, and the bundle must not ship a second React.
 */
import { build } from 'esbuild'
import { copyFile, mkdir, readFile, readdir, stat, writeFile } from 'node:fs/promises'
import { dirname, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..')
const pkg = JSON.parse(await readFile(resolve(root, 'package.json'), 'utf8'))

const stamp = (() => {
  const now = new Date()
  const pad = (value) => String(value).padStart(2, '0')
  return `${now.getFullYear()}-${pad(now.getMonth() + 1)}-${pad(now.getDate())} ${pad(now.getHours())}:${pad(now.getMinutes())}`
})()

const result = await build({
  entryPoints: [resolve(root, 'src/client/index.tsx')],
  bundle: true,
  write: false,
  format: 'iife',
  globalName: '__paperreaderBundle',
  platform: 'browser',
  target: ['es2022'],
  jsx: 'automatic',
  jsxImportSource: 'react',
  external: ['react', 'react-dom', 'react/jsx-runtime'],
  legalComments: 'none',
  logLevel: 'warning',
  absWorkingDir: root,
  define: {
    // Shown in the main sidebar so a stale browser bundle is identifiable at a glance.
    __PR_BUILD__: JSON.stringify(stamp),
    __PR_VERSION__: JSON.stringify(pkg.version ?? '0.0.0'),
  },
})

const body = result.outputFiles[0].text
const wrapper = `/* PaperReader — browser half. Generated by build/build.mjs; do not edit. */
window.__ModuleLoader__.load({ id: "dsh-paper-read", factory: (require) => {
${body}
return __paperreaderBundle;
}});
`

await mkdir(resolve(root, 'dist/client'), { recursive: true })
await writeFile(resolve(root, 'dist/client/client.js'), wrapper, 'utf8')

// pdf.js runs its parser in a worker; the host serves this file from `dist/vendor/`.
const workerSource = resolve(root, 'node_modules/pdfjs-dist/build/pdf.worker.min.mjs')
await mkdir(resolve(root, 'dist/vendor'), { recursive: true })
await copyFile(workerSource, resolve(root, 'dist/vendor/pdf.worker.min.mjs'))
const workerBytes = (await stat(resolve(root, 'dist/vendor/pdf.worker.min.mjs'))).size

// KaTeX ships its own CSS and font files. The host serves them from
// `dist/vendor/katex/`, so formula rendering stays offline and the browser
// resolves the font URLs against the plugin's static route.
const katexDist = resolve(root, 'node_modules/katex/dist')
const katexOut = resolve(root, 'dist/vendor/katex')
await mkdir(resolve(katexOut, 'fonts'), { recursive: true })
const katexCss = await readFile(resolve(katexDist, 'katex.min.css'), 'utf8')
await writeFile(
  resolve(katexOut, 'katex.min.css'),
  katexCss.replace(/url\(fonts\//g, 'url(/api/paperreader/static/katex/fonts/'),
  'utf8',
)
const katexFonts = await readdir(resolve(katexDist, 'fonts'))
for (const font of katexFonts) {
  await copyFile(resolve(katexDist, 'fonts', font), resolve(katexOut, 'fonts', font))
}

const bytes = Buffer.byteLength(wrapper)
const requires = [...new Set([...wrapper.matchAll(/require\("([^"]+)"\)/g)].map((m) => m[1]))]
console.log(`dist/client/client.js  ${(bytes / 1024).toFixed(1)} KiB`)
console.log(`dist/vendor/pdf.worker.min.mjs  ${(workerBytes / 1024).toFixed(1)} KiB`)
console.log(`externals  ${requires.join(', ') || '(none)'}`)
